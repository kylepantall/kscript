using System.Diagnostics.CodeAnalysis;
using System.Text.Json.Serialization;

namespace KScript.Http
{
    /// <summary>
    /// Source-generated JSON for OpenAPI documents, so kscript openapi works without reflection (Native AOT). A
    /// document is maps, lists and scalars; every type that appears in one is listed here, and writing any other
    /// type fails, in tests as well as in AOT builds.
    /// </summary>
    [JsonSerializable(typeof(Dictionary<string, object>))]
    [JsonSerializable(typeof(List<object>))]
    [JsonSerializable(typeof(List<string>))]
    [JsonSerializable(typeof(string[]))]
    [JsonSerializable(typeof(object[]))]
    [JsonSerializable(typeof(string))]
    [JsonSerializable(typeof(bool))]
    [JsonSerializable(typeof(int))]
    [JsonSerializable(typeof(long))]
    [JsonSerializable(typeof(double))]
    [JsonSerializable(typeof(decimal))]
    [ExcludeFromCodeCoverage(Justification = "Generated by the System.Text.Json source generator.")]
    internal sealed partial class OpenApiJsonContext : JsonSerializerContext
    {
    }
}
