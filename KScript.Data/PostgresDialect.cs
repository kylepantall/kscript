using System.Collections.Concurrent;
using System.Data.Common;

using KScript.Runtime;

using Npgsql;

namespace KScript.Data
{
    /// <summary>
    /// PostgreSQL, through Npgsql. Emails compare without minding case through a case-insensitive ICU collation,
    /// kscript_nocase, made the first time a table needs it.
    /// </summary>
    internal sealed class PostgresDialect : Dialect
    {
        public static readonly PostgresDialect Instance = new PostgresDialect();

        internal const string Collation = "kscript_nocase";

        /// <summary>One data source (and so one pool) per connection string. The slim builder keeps Native AOT builds free of reflection.</summary>
        private static readonly ConcurrentDictionary<string, NpgsqlDataSource> Sources = new ConcurrentDictionary<string, NpgsqlDataSource>(StringComparer.Ordinal);

        public override string Name => "postgres";

        public override DbConnection Open(DatabaseSettings settings)
        {
            NpgsqlDataSource source = Sources.GetOrAdd(settings.ConnectionString, cs => new NpgsqlSlimDataSourceBuilder(cs).Build());
            return source.OpenConnection();
        }

        public override void ClearPools()
        {
            foreach (string key in Sources.Keys.ToList())
            {
                if (Sources.TryRemove(key, out NpgsqlDataSource source)) source.Dispose();
            }
        }

        public override string ColumnType(Column column, bool indexed) => column.Kind switch
        {
            ColumnKind.Integer => "BIGINT",
            ColumnKind.Real => "DOUBLE PRECISION",
            ColumnKind.Bool => "BOOLEAN",
            ColumnKind.Date => "TIMESTAMP(6)",
            _ => "TEXT",
        };

        public override object Bool(bool value) => value;

        /// <summary>Postgres puts nulls last going up: they are put first, as SQLite and MySQL have them.</summary>
        public override string Direction(bool descending) => descending ? " DESC NULLS LAST" : " ASC NULLS FIRST";

        /// <summary>A timestamp holds the clock time as it is, like SQLite's text: Npgsql only writes unzoned times to it.</summary>
        public override object Date(DateTime value) => DateTime.SpecifyKind(value, DateTimeKind.Unspecified);

        /// <summary>
        /// ILIKE, so case doesn't matter, as in SQLite. The column is read as plain text first: LIKE can't use the
        /// case-insensitive collation emails have.
        /// </summary>
        public override void Like(SqlWriter w, SqlExpr left, SqlExpr right)
        {
            w.Append("CAST(").Expr(left).Append(" AS TEXT) COLLATE \"default\" ILIKE ").Expr(right, nested: true).Append(" ESCAPE '\\'");
        }

        /// <summary>
        /// Postgres regexes take their flags as embedded options. Without s, . doesn't match a new line, and with m, ^ and
        /// $ match at each line: as in .NET.
        /// </summary>
        public override void Matches(SqlWriter w, SqlExpr target, RegexValue regex)
        {
            bool multiline = regex.Flags.Contains('m');
            bool dotAll = regex.Flags.Contains('s');
            string options = (multiline ? (dotAll ? "w" : "n") : (dotAll ? "s" : "p"))
                + (regex.Flags.Contains('i') ? "i" : string.Empty) + (regex.Flags.Contains('x') ? "x" : string.Empty);
            w.Append("CAST(").Expr(target).Append(" AS TEXT) COLLATE \"default\" ~ ").Value("(?" + options + ")" + regex.Pattern);
        }

        protected override IEnumerable<string> Prepare(ModelInfo model)
        {
            if (model.Columns.Any(c => c.Kind == ColumnKind.Email))
                yield return $"CREATE COLLATION IF NOT EXISTS {Quote(Collation)} (provider = icu, locale = 'und-u-ks-level2', deterministic = false)";
        }

        protected override string AutoKey => "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";

        // A column's collation comes after its type in Postgres: it is added to the type in ColumnDefinition below.
        protected override string CaseInsensitive => string.Empty;

        protected override string ColumnDefinition(Column c, bool indexed)
        {
            string definition = base.ColumnDefinition(c, indexed);
            if (c.Kind != ColumnKind.Email || c.AutoIncrement) return definition;
            string head = Quote(c.Name) + " " + ColumnType(c, indexed);
            return head + " COLLATE " + Quote(Collation) + definition.Substring(head.Length);
        }

        public override string TablesQuery =>
            "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name";

        // https://www.postgresql.org/docs/current/errcodes-appendix.html
        public override bool IsBusy(Exception error) => error is PostgresException p && p.SqlState is "40001" or "40P01" or "55P03";

        public override KScriptException Translate(Exception error, string table)
        {
            if (error is not PostgresException e) return null;
            table ??= e.TableName;
            return e.SqlState switch
            {
                "23505" => UniqueViolation(e, table, FieldsOfIndex(table, e.ConstraintName)),
                "23503" => ForeignKeyViolation(e, table),
                _ => QueryError(e, e.MessageText),
            };
        }
    }
}
