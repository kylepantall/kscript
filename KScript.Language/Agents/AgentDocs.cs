        /// <summary>index.md: one line per project symbol, by file, within <see cref="IndexBudget"/>.</summary>
        public static string Index(AgentProject project)
        {
            var w = new StringBuilder();
            w.Append($"# {project.Name}: symbols\n\n");
            w.Append("Generated by `kscript agents` from the code: each line is a signature (parameter types, defaults, return type; a type's fields and rules), what it does (its `///` doc), the errors it throws and the call graph. `prefer`, `avoid` and `pitfall` come from optional doc tags. `:N` is the line.\n");
            var entries = new List<string>();
            if (project.Routes != null)
            {
                entries.Add("\n## Routes (kscript routes)\n\n```text\n" + project.Routes + "\n```\n");
            }
            if (project.Symbols.Count == 0)
            {
                entries.Add("\nNo top-level functions, types, enums or consts yet.\n");
            }
            foreach (IGrouping<string, AgentSymbol> file in project.Symbols.GroupBy(s => s.File))
            {
                entries.Add($"\n## {file.Key}\n\n");
                entries.AddRange(file.Select(SymbolLine));
            }
            return Join(w.ToString(), entries, IndexBudget, "symbols");
        }

        internal static string SymbolLine(AgentSymbol s)
        {
            var e = new StringBuilder();
            e.Append($"- `{s.Signature}`{(s.Deprecated ? " (deprecated)" : string.Empty)}{(s.Summary != null ? " " + s.Summary : string.Empty)} :{s.Line}\n");
            foreach (string p in s.Prefer) e.Append($"  - prefer: {Summarize(p)}\n");
            foreach (string a in s.Avoid) e.Append($"  - avoid: {Summarize(a)}\n");
            foreach (string p in s.Pitfalls) e.Append($"  - pitfall: {Summarize(p)}\n");
            if (s.Throws.Count > 0) e.Append($"  - throws: {string.Join(", ", s.Throws)}\n");
            if (s.Calls.Count > 0) e.Append($"  - calls: {string.Join(", ", s.Calls.Take(8))}{(s.Calls.Count > 8 ? ", …" : string.Empty)}\n");
            if (s.CalledBy.Count > 0) e.Append($"  - used by: {string.Join(", ", s.CalledBy.Take(8))}{(s.CalledBy.Count > 8 ? ", …" : string.Empty)}\n");
            if (s.Example != null) e.Append($"  - e.g. `{s.Example}`\n");
            return e.ToString();
        }

        /// <summary>A package's file: its commands, methods by type and elements, one line each, within <see cref="PackageBudget"/>.</summary>
        public static string Package(string package, LanguageCatalog catalog = null, string format = MakeSettings.KScriptFormat)
        {
            catalog ??= LanguageCatalog.Default;
            bool xml = format == MakeSettings.XmlFormat;
            var w = new StringBuilder();
            string description = catalog.Packages.TryGetValue(package, out string d) ? Summarize(d, 200) : null;
            w.Append($"# {package}\n\n");
            if (description != null) w.Append(description).Append('\n');
            w.Append(package == "KScript.Core" ? "Always available.\n" : xml ? $"Import with `<import package=\"{package}\" />`.\n" : $"Import with `import {package}`.\n");

            var entries = new List<string>();
            List<CallableInfo> commands = catalog.Commands.Where(c => c.Package == package).OrderBy(c => c.Name, StringComparer.Ordinal).ToList();
            if (commands.Count > 0)
            {
                entries.Add("\n## Commands\n\n");
                entries.AddRange(commands.Select(CallableLine));
            }
            foreach (IGrouping<string, CallableInfo> type in catalog.Methods.Where(m => m.Package == package).GroupBy(m => m.ReceiverType).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                entries.Add($"\n## {type.Key} methods\n\n");
                entries.AddRange(type.OrderBy(m => m.Name, StringComparer.Ordinal).Select(CallableLine));
            }
            List<ElementInfo> elements = catalog.Elements.Where(e => e.Package == package && (xml || !CodeSyntax.Contains(e.Name)))
                .OrderBy(e => e.Name, StringComparer.Ordinal).ToList();
            if (elements.Count > 0)
            {
                entries.Add(xml ? "\n## Elements\n\n" : "\n## Statements\n\n");
                entries.AddRange(elements.Select(e => ElementLine(e, xml)));
            }
            if (entries.Count == 0)
            {
                w.Append("\nNothing to call: this package changes how other things behave.\n");
                return w.ToString();
            }
            return Join(w.ToString(), entries, PackageBudget, "entries");
        }

        internal static string CallableLine(CallableInfo c)
        {
            var e = new StringBuilder();
            string label = c.Labels.FirstOrDefault() ?? c.Prefix + c.Name + "()";
            string returns = c.ReturnType != null && c.ReturnType != KType.Any ? ": " + c.ReturnType : string.Empty;
            string summary = Summarize(c.Agent?.Llm ?? c.Description);
            e.Append($"- `{label}{returns}`{(summary != null ? " " + summary : string.Empty)}\n");
            AppendNotes(e, c.Agent);
            // Examples are written in either format; ones that start with an element are XML, so leave them to the MCP server.
            string example = ShortExample(c.Example);
            if (example != null && !example.StartsWith("<", StringComparison.Ordinal) && c.Agent?.Prefer == null) e.Append($"  - e.g. `{example}`\n");
            return e.ToString();
        }

        /// <summary>Core elements that .kscript writes as syntax (if, for, fn...), which AGENTS.md's crash course shows.</summary>
        private static readonly HashSet<string> CodeSyntax = new HashSet<string>(StringComparer.Ordinal)
        {
            "kscript", "if", "elif", "else", "for", "while", "match", "case", "default", "try", "catch", "finally", "break", "continue",
            "return", "fn", "let", "set", "const", "enum", "type", "field", "do", "import", "echo", "throw", "exit",
        };

        internal static string ElementLine(ElementInfo el, bool xml)
        {
            var e = new StringBuilder();
            IEnumerable<string> attributes = el.Attributes.Select(a => a.Required ? a.Name : a.Name + "?");
            string usage = xml
                ? $"<{el.Name}{string.Concat(attributes.Select(a => " " + a))}>"
                : $"{el.Name}({string.Join(", ", attributes)})";
            string summary = Summarize(el.Agent?.Llm ?? el.Description);
            e.Append($"- `{usage}`{(summary != null ? " " + summary : string.Empty)}\n");
            AppendNotes(e, el.Agent);
            return e.ToString();
        }

        private static void AppendNotes(StringBuilder e, AgentNotes notes)
        {
            if (notes == null) return;
            if (notes.Prefer != null) e.Append($"  - prefer: {Summarize(notes.Prefer)}\n");
            if (notes.Avoid != null) e.Append($"  - avoid: {Summarize(notes.Avoid)}\n");
            if (notes.Pitfall != null) e.Append($"  - pitfall: {Summarize(notes.Pitfall)}\n");
        }

        /// <summary>Adds entries after a header until the budget runs out, then says how many were left out and where to find them.</summary>
        private static string Join(string header, List<string> entries, int budget, string what)
        {
            var w = new StringBuilder(header);
            int shown = 0;
            foreach (string entry in entries)
            {
                if (w.Length + entry.Length > budget && shown > 0)
                {
                    break;
                }
                w.Append(entry);
                shown++;
            }
            if (shown < entries.Count)
            {
                // Headings don't count: only the entries under them.
                w.Append($"\n… {entries.Skip(shown).Count(e => e.StartsWith("- ", StringComparison.Ordinal))} more {what} left out to keep this file short. Use `lookup` or `search_docs` on the `kscript mcp` server, or `kscript docs`, for the rest.\n");
            }
            return w.ToString();
        }

        /// <summary>Cuts text to a budget at a line, ending with a pointer to the MCP server.</summary>
        private static string Fit(string text, int budget)
        {
            if (text.Length <= budget)
            {
                return text;
            }
            string note = "\n… cut to keep this file short. Use the `kscript mcp` server for the rest.\n" + End + "\n";
            int cut = text.LastIndexOf('\n', Math.Max(0, budget - note.Length));
            return text.Substring(0, Math.Max(0, cut)) + note;
        }

