    /// <summary>One of the project's own functions, types, enums or constants, as a coding agent sees it.</summary>
    public sealed class AgentSymbol
    {
        /// <summary>fn, type, enum or const.</summary>
        public string Kind { get; init; }

        public string Name { get; init; }

        /// <summary>How to use it, such as <c>@add(tasks, title: string)</c> or <c>enum Size { small, large }</c>.</summary>
        public string Signature { get; init; }

        /// <summary>The one line an agent reads: <c>@llm</c>, else the first sentence of the doc comment. Capped.</summary>
        public string Summary { get; init; }

        public IReadOnlyList<string> Prefer { get; init; } = Array.Empty<string>();
        public IReadOnlyList<string> Avoid { get; init; } = Array.Empty<string>();
        public IReadOnlyList<string> Pitfalls { get; init; } = Array.Empty<string>();

        /// <summary>The first @example, when it fits on one short line.</summary>
        public string Example { get; init; }

        public bool Deprecated { get; init; }

        /// <summary>The project functions it calls (from the code), as @names.</summary>
        public IReadOnlyList<string> Calls { get; init; } = Array.Empty<string>();

        /// <summary>The project functions that call it, filled in once every file is read.</summary>
        public List<string> CalledBy { get; } = new List<string>();

        /// <summary>The error types its body throws (throw Validation "...").</summary>
        public IReadOnlyList<string> Throws { get; init; } = Array.Empty<string>();

        /// <summary>The file it is declared in, relative to the project, with / separators.</summary>
        public string File { get; init; }

        /// <summary>The line it is declared on, from 1.</summary>
        public int Line { get; init; }
    }

    /// <summary>What <c>kscript agents</c> knows about a project: its packages and its own symbols.</summary>
    public sealed class AgentProject
    {
        public string Root { get; init; }

        public string Name { get; init; }

        /// <summary>kscript or xml: the format the project writes scripts in (make.format).</summary>
        public string Format { get; init; } = MakeSettings.KScriptFormat;

        /// <summary>Every package a script in the project uses, KScript.Core first.</summary>
        public IReadOnlyList<string> Packages { get; init; } = new[] { "KScript.Core" };

        public IReadOnlyList<AgentSymbol> Symbols { get; init; } = Array.Empty<AgentSymbol>();

        /// <summary>The project's scripts (not tests or pages), relative, with / separators.</summary>
        public IReadOnlyList<string> Scripts { get; init; } = Array.Empty<string>();

        public int Tests { get; init; }

        public int Pages { get; init; }

        /// <summary>The site's routes as <c>kscript routes</c> prints them, or null when there are none.</summary>
        public string Routes { get; init; }

        /// <summary>app.main from kscript.json, when set.</summary>
        public string Main { get; init; }

        public bool IsXml => Format == MakeSettings.XmlFormat;
    }

    /// <summary>
    /// Writes compact docs for coding agents: AGENTS.md (a crash course in KScript, the mistakes to avoid, the commands
    /// to run and the project's packages) and .kscript/agents (one line per project symbol in index.md, and one file per
    /// imported package). Everything has a budget, so the docs stay cheap to read; what doesn't fit is left to
    /// <c>kscript mcp</c>. Only the part of AGENTS.md between <see cref="Begin"/> and <see cref="End"/> is generated,
    /// so notes written around it are kept.
    /// </summary>
    public static class AgentDocs
    {
        public const string AgentsFile = "AGENTS.md";

        /// <summary>The folder for the index and package files, relative to the project root.</summary>
        public const string Folder = ".kscript/agents";

        public const string Begin = "<!-- kscript agents: begin. Generated by `kscript agents` (and the editor on save); edits between these lines are replaced. -->";
        public const string End = "<!-- kscript agents: end -->";

        /// <summary>The longest summary line, in characters.</summary>
        public const int SummaryLimit = 120;

        /// <summary>The longest example kept, in characters.</summary>
        public const int ExampleLimit = 100;

        /// <summary>Budgets in characters (about four to a token): AGENTS.md's section, index.md and each package file.</summary>
        public static int AgentsBudget = 7000;
        public static int IndexBudget = 16000;
        public static int PackageBudget = 28000;

        private static readonly HashSet<string> SkippedFolders = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "bin", "obj", "node_modules", "dist", "_templates" };

        /// <summary>A rough token count: about four characters to a token.</summary>
        public static int EstimateTokens(string text) => string.IsNullOrEmpty(text) ? 0 : (text.Length + 3) / 4;

        /// <summary>The project folder for a path: the nearest folder with a kscript.json, else the folder itself.</summary>
        public static string FindRoot(string path)
        {
            string full = Path.GetFullPath(path);
            string config = ProjectConfig.Find(full);
            if (config != null)
            {
                return Path.GetDirectoryName(config);
            }
            return Directory.Exists(full) ? full : Path.GetDirectoryName(full);
        }

        /// <summary>True when the project has agent docs, so the editor should keep them up to date.</summary>
        public static bool IsEnabled(string root) => root != null && Directory.Exists(Path.Combine(root, Folder));

        #region Reading the project

        /// <summary>Reads a project: its settings, its scripts' top-level symbols and the packages they use.</summary>
        /// <param name="format">kscript or xml, to override make.format (kscript convert passes the format it converted to).</param>
        /// <param name="skip">Full paths of scripts to leave out, such as the originals kscript convert just replaced.</param>
        public static AgentProject Read(string root, LanguageCatalog catalog = null, string format = null, ISet<string> skip = null)
        {
            catalog ??= LanguageCatalog.Default;
            root = Path.GetFullPath(root);
            string configFile = Path.Combine(root, ProjectConfig.FileName);
            ProjectConfig config = File.Exists(configFile) ? ProjectConfig.Load(configFile) : null;

            var packages = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "KScript.Core" };
            foreach (string p in config?.Packages ?? new List<string>())
            {
                if (catalog.FindPackage(p) is string found) packages.Add(found);
            }

            var symbols = new List<AgentSymbol>();
            var scripts = new List<string>();
            int tests = 0, pages = 0;
            foreach (string file in FilesUnder(root).Where(f => skip?.Contains(f) != true).OrderBy(f => f, StringComparer.Ordinal))
            {
                string relative = Path.GetRelativePath(root, file).Replace('\\', '/');
                bool page = file.EndsWith(".html", StringComparison.OrdinalIgnoreCase) || file.EndsWith(".md", StringComparison.OrdinalIgnoreCase);
                if (page)
                {
                    pages++;
                    continue;
                }
                if (TestSettings.IsTestFileName(file))
                {
                    tests++;
                    continue;
                }
                string text = File.ReadAllText(file);
                if (file.EndsWith(".xml", StringComparison.OrdinalIgnoreCase) && !file.EndsWith(".ks.xml", StringComparison.OrdinalIgnoreCase)
                    && !text.Contains("<kscript", StringComparison.Ordinal))
                {
                    continue;
                }
                scripts.Add(relative);
                DocumentAnalysis analysis = Analyzer.Analyze(text, file, catalog: catalog);
                foreach (string p in analysis.ImportedPackages) packages.Add(p);
                symbols.AddRange(SymbolsOf(analysis, relative));
            }

            // The call graph: who calls each function, from the calls found in each one's body.
            var byName = symbols.Where(x => x.Kind == "fn").GroupBy(x => x.Name, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.ToList(), StringComparer.Ordinal);
            foreach (AgentSymbol caller in symbols)
            {
                foreach (string call in caller.Calls)
                {
                    if (byName.TryGetValue(call.TrimStart('@'), out List<AgentSymbol> callees))
                    {
                        foreach (AgentSymbol callee in callees.Where(c => c != caller && !c.CalledBy.Contains("@" + caller.Name))) callee.CalledBy.Add("@" + caller.Name);
                    }
                }
            }

            return new AgentProject
            {
                Root = root,
                Name = config?.Name ?? Path.GetFileName(root.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)),
                Format = (format ?? config?.Make.Format) == MakeSettings.XmlFormat ? MakeSettings.XmlFormat : MakeSettings.KScriptFormat,
                Packages = packages.OrderBy(p => p == "KScript.Core" ? 0 : 1).ThenBy(p => p, StringComparer.Ordinal).ToList(),
                Symbols = symbols,
                Scripts = scripts,
                Tests = tests,
                Pages = pages,
                Main = config?.App.Main,
                Routes = RoutesOf(config?.SiteRoot ?? root, config, skip),
            };
        }

        /// <summary>The route table of a site with KScript.Http route files, or null.</summary>
        private static string RoutesOf(string site, ProjectConfig config, ISet<string> skip)
        {
            var table = new StringWriter();
            if (KScript.Http.HttpServer.ListRoutes(site, config, table, TextWriter.Null, plain: true) != 0)
            {
                return null;
            }
            // Route files kscript convert just replaced are still on disk, so name their new versions instead.
            string text = table.ToString().Replace("\r\n", "\n").TrimEnd();
            foreach (string old in skip ?? new HashSet<string>())
            {
                string name = Path.GetRelativePath(site, old).Replace('\\', '/');
                text = text.Replace(" " + name + ":", " " + ScriptConverter.ConvertedPath(name) + ":", StringComparison.Ordinal);
            }
            return text;
        }

        private static IEnumerable<string> FilesUnder(string root)
        {
            var pending = new Stack<string>();
            pending.Push(root);
            while (pending.Count > 0)
            {
                string dir = pending.Pop();
                foreach (string sub in Directory.EnumerateDirectories(dir))
                {
                    string name = Path.GetFileName(sub);
                    if (!name.StartsWith(".", StringComparison.Ordinal) && !SkippedFolders.Contains(name)) pending.Push(sub);
                }
                foreach (string file in Directory.EnumerateFiles(dir))
                {
                    if (IsScriptOrPage(file)) yield return file;
                }
            }
        }

        private static bool IsScriptOrPage(string file) =>
            new[] { ".kscript", ".ks", ".ks.xml", ".xml", ".html", ".md" }.Any(e => file.EndsWith(e, StringComparison.OrdinalIgnoreCase))
            && !string.Equals(Path.GetFileName(file), AgentsFile, StringComparison.OrdinalIgnoreCase)
            && !string.Equals(Path.GetFileName(file), "README.md", StringComparison.OrdinalIgnoreCase);

        /// <summary>The top-level fn, type, enum and const declarations of a script, minus _names and @agent hide.</summary>
        public static IEnumerable<AgentSymbol> SymbolsOf(DocumentAnalysis analysis, string file)
        {
            foreach (Symbol s in analysis.Symbols)
            {
                MarkupElement e = s.DeclaringElement;
                if (s.SourcePath != null || e == null || e.Parent?.Parent != null || s.Name == null || s.Name.StartsWith("_", StringComparison.Ordinal))
                {
                    continue;
                }
                string kind = e.Name switch
                {
                    "fn" when s.Kind == SymbolKind.Function => "fn",
                    "type" => "type",
                    "enum" => "enum",
                    "const" => "const",
                    "let" when s.IsConst => "const",
                    _ => null,
                };
                if (kind == null)
                {
                    continue;
                }
                // The element's own doc, not the symbol's description, which the analyzer fills in for types.
                DocComment doc = DocComment.Parse(e.Documentation);
                if (doc?.AgentHidden == true)
                {
                    continue;
                }
                yield return new AgentSymbol
                {
                    Kind = kind,
                    Name = s.Name,
                    Signature = SignatureOf(s, kind),
                    Summary = Summarize(doc?.Llm ?? doc?.Summary),
                    Prefer = doc?.Prefer ?? Array.Empty<string>(),
                    Avoid = doc?.Avoid ?? Array.Empty<string>(),
                    Pitfalls = doc?.Pitfalls ?? Array.Empty<string>(),
                    Example = ShortExample(doc?.Examples.FirstOrDefault()),
                    Deprecated = doc?.Deprecated != null,
                    Calls = kind == "fn" ? CallsIn(analysis, s) : Array.Empty<string>(),
                    Throws = kind == "fn" ? ThrowsIn(e) : Array.Empty<string>(),
                    File = file,
                    Line = analysis.Source.GetPosition(s.DeclarationSpan.Start).Line + 1,
                };
            }
        }

        /// <summary>The other functions a function's body calls: its own file's and imported ones.</summary>
        private static IReadOnlyList<string> CallsIn(DocumentAnalysis analysis, Symbol fn)
        {
            TextSpan body = fn.DeclaringElement.Span;
            return analysis.References
                .Where(r => !r.IsDeclaration && r.Symbol != fn && r.Symbol.Kind == SymbolKind.Function && body.Contains(r.Span.Start))
                .Select(r => "@" + r.Symbol.Name).Distinct(StringComparer.Ordinal).ToList();
        }

        /// <summary>The error types thrown in a function's body (Error when a throw names none).</summary>
        private static IReadOnlyList<string> ThrowsIn(MarkupElement fn) =>
            Descendants(fn).Where(x => x.Name == "throw")
              .Select(x => x.GetAttributeValue("type")?.Trim() is string t && t.Length > 0 ? t : "Error")
              .Distinct(StringComparer.Ordinal).ToList();

        private static IEnumerable<MarkupElement> Descendants(MarkupElement e) =>
            e.ChildElements.SelectMany(c => new[] { c }.Concat(Descendants(c)));

        private static string SignatureOf(Symbol s, string kind) => kind switch
        {
            "fn" => s.TypedSignature,
            "enum" => $"enum {s.Name} {{ {string.Join(", ", s.EnumValues ?? new List<string>())} }}",
            "type" => TypeSignature(s),
            _ => $"const ${s.Name}" + (s.Shape.IsVague ? string.Empty : ": " + s.Shape.Display()),
        };

        /// <summary>
        /// A type with its fields as written in the code: <c>type Repo { name: string, stars: int from
        /// stargazers_count, topics: string[] = [], label => ... }</c>. Every other attribute of a field (such as a
        /// validation rule) is kept as <c>name: value</c>, so the agent sees the rules the data must meet.
        /// </summary>
        private static string TypeSignature(Symbol s)
        {
            MarkupElement type = s.DeclaringElement;
            var fields = new List<string>();
            foreach (MarkupElement field in type.ChildElements.Where(f => f.Name == "field"))
            {
                string name = field.GetAttributeValue("name")?.Trim();
                if (string.IsNullOrEmpty(name)) continue;
                string optional = IsYes(field.GetAttributeValue("optional")) ? "?" : string.Empty;
                if (field.GetAttributeValue("value") is string computed)
                {
                    fields.Add($"{name} => {computed.Trim()}");
                    continue;
                }
                var f = new StringBuilder(name + optional + ": " + (field.GetAttributeValue("type")?.Trim() ?? "any"));
                if (field.GetAttributeValue("from") is string from) f.Append(" from ").Append(from.Trim());
                if (field.GetAttributeValue("default") is string value) f.Append(" = ").Append(value.Trim());
                foreach (MarkupAttribute rule in field.Attributes.Where(a => !FieldBasics.Contains(a.Name)))
                {
                    f.Append($" {rule.Name}: {rule.ValueText?.Trim()}");
                }
                fields.Add(f.ToString());
            }
            if (fields.Count == 0 && type.GetAttributeValue("fields") is string inline)
            {
                fields.AddRange(inline.Split(',').Select(x => x.Trim()).Where(x => x.Length > 0));
            }
            string options = string.Concat(type.Attributes.Where(a => a.Name is "extra" or "sample").Select(a => $"({a.Name}: {a.ValueText?.Trim()})"));
            return fields.Count == 0 ? $"type {s.Name}{options} {{ }}" : $"type {s.Name}{options} {{ {string.Join(", ", fields)} }}";
        }

        private static readonly HashSet<string> FieldBasics = new HashSet<string>(StringComparer.Ordinal) { "name", "type", "from", "default", "optional", "value", "description" };

        private static bool IsYes(string value) => value?.Trim() is "yes" or "true";

        /// <summary>
        /// The first sentence (or line) of some doc text, without Markdown emphasis, cut to <see cref="SummaryLimit"/>
        /// characters at a word. Null for no text.
        /// </summary>
        public static string Summarize(string text, int limit = SummaryLimit)
        {
            if (string.IsNullOrWhiteSpace(text))
            {
                return null;
            }
            string line = text.Replace("\r", string.Empty).Split("\n\n")[0].Replace('\n', ' ').Replace("**", string.Empty).Trim();
            int stop = line.IndexOf(". ", StringComparison.Ordinal);
            if (stop > 0)
            {
                line = line.Substring(0, stop + 1);
            }
            if (line.Length <= limit)
            {
                return line;
            }
            int space = line.LastIndexOf(' ', limit - 1);
            return line.Substring(0, space > limit / 2 ? space : limit - 1).TrimEnd(',', ';', ':') + "…";
        }

        private static string ShortExample(string example) =>
            example == null || example.Contains('\n') || example.Length > ExampleLimit ? null : example.Trim();

