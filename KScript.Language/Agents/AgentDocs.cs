        /// <summary>The generated part of AGENTS.md, markers included.</summary>
        public static string AgentsSection(AgentProject project, LanguageCatalog catalog = null)
        {
            catalog ??= LanguageCatalog.Default;
            var w = new StringBuilder();
            w.Append(Begin).Append('\n');
            w.Append("# KScript for agents\n\n");
            w.Append($"This project ({project.Name}) is written in KScript, a small scripting language. ");
            w.Append(project.IsXml
                ? "Scripts are XML (`.ks.xml`): elements for statements, `{ }` and attributes for expressions. Tests end in `.test.ks.xml`.\n\n"
                : "Scripts are `.kscript` files (code syntax, shown below). Tests end in `.test.kscript`.\n\n");

            w.Append($"Start with the [function and type index]({Folder}/index.md) and [package references]({Folder}/packages/).\n\n");
            w.Append("Use `search_docs` to find KScript APIs and `lookup` to confirm signatures and examples. In VS Code, the KScript extension provides these tools through KScript Docs. Other MCP clients can use `kscript mcp`.\n\n");
            int guidanceAt = w.Length;
            w.Append("## Syntax\n\n");
            w.Append(project.IsXml ? "```xml\n" + CrashCourseXml() + "\n```\n\n" : "```kscript\n" + CrashCourse + "\n```\n\n");
            w.Append(Rules);

            w.Append("\n## Required project conventions\n\n");
            w.Append("- Read `kscript.json` and a neighboring feature. Follow the configured syntax and paths, reuse existing code, and verify APIs in the package reference or MCP.\n");
            w.Append("- Type domain values at the boundary. Use built-in types such as `email`, `uuid` and `duration`. Define shared domain rules once with `kscript make native`. Put normalization, validation and value methods on the type. Project natives load from the manifest’s `natives` setting (default `natives/`).\n");
            w.Append("- Use records for known shapes (`kscript make type`) and models and migrations for persisted rows. Validate external JSON with `as: Type` where supported. Use `map` for open keys and `any` for genuinely dynamic values.\n");
            bool http = project.Packages.Contains("KScript.Http") || project.Routes != null;
            bool web = project.Packages.Contains("KScript.Web") || project.Pages > 0;
            if (http)
                w.Append("- Use `kscript make route` for routing and a controller for the action. For a known JSON body, generate a request type with `kscript make request`, import it, and type the controller’s `json` parameter so the framework validates it.\n");
            if (web)
            {
                w.Append("- Keep presentation in views or components. Put reusable domain behavior on the type or in a library module.\n");
                w.Append("- Build interactive pages with component state and live actions. Use client directives and actions for browser-only behavior.\n");
                w.Append("- Use `kscript make css` for `.ks.css` and link its `.css` URL. Use `.ks.scss` when the project builds Sass.\n");
            }
            w.Append("- Run generators from the project so they follow its `paths` settings. Catch specific errors where recovery or reporting belongs. Rethrow when the caller owns recovery.\n");

            WriteTaskGuide(w, project, web, http);

            w.Append("\n## Mistakes to avoid\n\n");
            w.Append(Mistakes);
            if (project.IsXml)
            {
                w.Append("- XML attributes can't hold a raw `<`: write `lt`, `le`, `gt`, `ge`, or use `<if $n > 3>` shorthand start tags.\n");
            }

            w.Append("\n## Before finishing a change\n\n");
            w.Append("1. Add tests for changed behavior, rejected inputs and recovery.\n");
            w.Append("2. Run `kscript check --output json --warnings-as-errors`. For KS5016, handle the escaping error at the appropriate boundary.\n");
            string testPattern = project.IsXml ? "*.test.ks.xml" : "*.test.kscript";
            w.Append(project.Tests > 0 ? $"3. Run `kscript test` (runs the {project.Tests} test file{(project.Tests == 1 ? string.Empty : "s")}).\n" : $"3. Run `kscript test` (runs `{testPattern}` files).\n");
            w.Append("4. Run `kscript fmt --check` and `kscript agents`. Report results and any skipped checks.\n");

            w.Append("\n## This project\n\n");
            if (project.Main != null)
            {
                w.Append($"- Entry point: `{project.Main}` (kscript.json app.main).\n");
            }
            w.Append($"- {Count(project.Scripts.Count, "script")}, {Count(project.Tests, "test file")}{(project.Pages > 0 ? ", " + Count(project.Pages, "page") : string.Empty)}. ");
            int fns = project.Symbols.Count(s => s.Kind == "fn");
            int others = project.Symbols.Count - fns;
            w.Append($"The index lists {Count(fns, "function")} and {Count(others, "type, enum and const", "types, enums and consts")}.\n");
            w.Append("- Packages:\n");
            foreach (string package in project.Packages)
            {
                string description = catalog.Packages.TryGetValue(package, out string d) ? Summarize(d, 90) : null;
                w.Append($"  - `{package}`{(description != null ? ": " + description : string.Empty)}\n");
            }
            w.Append(End).Append('\n');
            // The raw string constants have the source file's line endings (CRLF in a Windows checkout).
            string generated = Fit(w.ToString().Replace("\r\n", "\n"), AgentsBudget);
            if (project.Markdown.Count == 0) return generated;

            // Keep project instructions whole. Budgets apply only to the generated reference.
            string guidance = "## Project guidance\n\n" + string.Join("\n\n", project.Markdown.Select(text => text.TrimEnd('\n'))) + "\n\n";
            return generated.Insert(Math.Min(guidanceAt, generated.IndexOf(End, StringComparison.Ordinal)), guidance);
        }

        private const string Guides = "https://github.com/kylepantall/kscript/blob/master/docs/";

        private static void WriteTaskGuide(StringBuilder w, AgentProject project, bool web, bool http)
        {
            bool auth = project.Packages.Contains("KScript.Auth");
            bool storage = project.Packages.Contains("KScript.Storage");
            if (!web && !http && !auth && !storage) return;

            w.Append("\n## Choose a feature for the task\n\n| Task | Use | Guide |\n| --- | --- | --- |\n");
            if (web)
            {
                w.Append($"| Clicks, forms and in-place updates | A `Component` with state and `@on-click`, `@on-submit` and `@bind`, or a `<live>` block | [Components]({Guides}components.md) |\n");
                w.Append($"| Browser-only work such as drag previews or reading files | A `KScriptLive.directive` or `KScriptLive.action`. Call a named live action when the server needs the result | [Client-side extensions]({Guides}components.md#client-side-extensions) |\n");
            }
            if (http)
                w.Append($"| JSON for another program | `kscript make route --api`, a controller and a typed request | [Routes and APIs]({Guides}http.md) |\n");
            if (auth)
                w.Append($"| Check sign-in or read the current user | `@is_signed_in()` and `@user()` | [Sign-in]({Guides}auth.md) |\n");
            if (storage)
                w.Append($"| Files owned by the app | `KScript.Storage` and `@storage()` | [App folders]({Guides}storage.md) |\n");
        }

        private static string Count(int n, string one, string many = null) => $"{n} {(n == 1 ? one : many ?? one + "s")}";

        /// <summary>A small program that shows most of the syntax. In XML projects it is converted.</summary>
        internal const string CrashCourse = """
            import KScript.IO // packages go at the top; KScript.Core is always there. Scripts: import "lib/x.kscript" as x

            const limit = 3
            // In a project, each type has its own file (types/task.kscript), and the scripts that use it import it.
            type Task {
              title: string
              done: bool = false
            }

            /// What the fn does, shown in hover. Tags: @param @returns @throws @example @llm @prefer @avoid @pitfall
            fn label(task: Task, mark: string = '-') => $mark + ' ' + $task.title->upper()

            fn open_tasks(tasks: Task[]) {
              if $tasks->is_empty() {
                return [] // return early rather than else
              }
              return $tasks->filter(fn(t) => not $t.done)->take($limit)
            }

            tasks = @exists('tasks.json') ? @read_json('tasks.json', as: 'Task[]') : []
            count = 0 // declare or change: no $ on the left
            for task in @open_tasks($tasks) {
              count += 1
              echo "{ $count }. { @label($task, mark: '*') }" // read with $, call with @
            }
            match $count {
              0 => echo 'Nothing to do'
              _ => echo "{$count} open"
            }
            try {
              @write_json('done.json', $tasks->filter(fn(t) => $t.done))
            } catch err when $err.type == 'IO' {
              throw Validation "Could not save: { $err.message }"
            }
            """;

        private static string CrashCourseXml()
        {
            ConversionResult xml = ScriptConverter.ToXml(CodeParser.Parse(CrashCourse), nameList: LanguageCatalog.Default.IsNameList);
            return (Formatter.Format(xml.Text, "crash.ks.xml")?.Text ?? xml.Text).TrimEnd('\n');
        }

        internal const string Rules = """
            - `$name` reads a variable; `name = value` sets it. `@name(...)` calls a fn or command; `$x->name(...)` calls a method; `$x.name` reads a field (a plain fact: `$response.status`, `$file.size`); `$x |> name()` pipes.
            - Text: write `"Hi { $name }"` with braces around expressions and `{{ }}` for literal braces. Lambdas: `fn(x) => $x * 2`.
            - Errors: use `guard $ready else { return }` for preconditions. Recover a value with `@load() catch FileNotFound => 'Missing'`. Share a handler across callers with `catch FileNotFound { return 'Missing' }` after a function. A null fallback propagates the original error.
            - Operators: `== !=` (loose) `=== !==` (strict) `< <= > >=` `and or not` `??` `?.` `a ? b : c` `in`. Ranges `0..10` exclude the end.
            - Arguments: the first (the subject) positional, the rest named: `@round($x, digits: 2)`. Flags are bare words: `recursive`, `not recursive`. Enums are `enum Size { small, large }`, and their values are bare: `@known_folder(downloads)`.
            - Lists of names are arrays: `use: [log, cors]`, never `"log, cors"`.
            - Types, models, enums, errors and jobs are named bare (`as: Task`, `User->create(name: 'Joan')`), and calling the name makes a value: `Task($data)`, `Task(title: 'x')`. An optional field is `due?: date`. Options go in brackets: `model User(timestamps, unique: [email]) { }`.
            - A package is named in its import: `import KScript.UI`, then `Window { }`. Core and the packages configured in `kscript.json` are available throughout the project. Import additional packages where used.
            - Lengths of time are durations, a number and a unit with no quotes: `timeout: 30s`, `ttl: 10m`, `wait(duration: 500ms)`. A plain number is seconds.

            """;

        internal const string Mistakes = """
            - Leaving out `$` when reading (`$count`, not `count`), or adding it when setting (`count = 1`, not `$count = 1`).
            - Write `and` and `or` for Boolean combinations. Use `not` or `!` to negate a condition, or `->!method()` to negate a method result.
            - Calling your own fn without `@`, or calling a package command without its `import` (`@read_json` needs `import KScript.IO`).
            - Inventing methods from other languages (`.length`, `.push()` on a string, `len()`): methods use `->` and are listed per package.
            - `else` after a branch that returns, breaks or continues: return early instead (KS6001).
            - Declaring a type in the file that uses it, or several in one file: each type, model, enum and error type gets its own file (`types/`, `models/`, `errors/`, request bodies in `requests/`), named after it in kebab-case, and the files that use it import it (KS6008).
            - `$Task` for a type, `due: date?` for an optional field, a model's options as lines of its block (KS6014), and `Task->from($data)` (gone: write `Task($data)`).

            """;

