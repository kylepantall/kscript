    /// <summary>One of the project's own functions, types, enums or constants, as a coding agent sees it.</summary>
    public sealed class AgentSymbol
    {
        /// <summary>fn, type, enum or const.</summary>
        public string Kind { get; init; }

        public string Name { get; init; }

        /// <summary>How to use it, such as <c>@add(tasks, title: string)</c> or <c>enum Size { small, large }</c>.</summary>
        public string Signature { get; init; }

        /// <summary>The one line an agent reads: <c>@llm</c>, else the first sentence of the doc comment. Capped.</summary>
        public string Summary { get; init; }

        public IReadOnlyList<string> Prefer { get; init; } = Array.Empty<string>();
        public IReadOnlyList<string> Avoid { get; init; } = Array.Empty<string>();
        public IReadOnlyList<string> Pitfalls { get; init; } = Array.Empty<string>();

        /// <summary>The first @example, when it fits on one short line.</summary>
        public string Example { get; init; }

        public bool Deprecated { get; init; }

        /// <summary>The project functions it calls (from the code), as @names.</summary>
        public IReadOnlyList<string> Calls { get; init; } = Array.Empty<string>();

        internal IReadOnlyList<(string File, string Name)> CallTargets { get; init; } = Array.Empty<(string, string)>();

        /// <summary>The project functions that call it, filled in once every file is read.</summary>
        public List<string> CalledBy { get; } = new List<string>();

        /// <summary>The error types its body throws (throw Validation "...").</summary>
        public IReadOnlyList<string> Throws { get; init; } = Array.Empty<string>();

        /// <summary>The file it is declared in, relative to the project, with / separators.</summary>
        public string File { get; init; }

        /// <summary>The line it is declared on, from 1.</summary>
        public int Line { get; init; }
    }

    /// <summary>What <c>kscript agents</c> knows about a project: its packages and its own symbols.</summary>
    public sealed class AgentProject
    {
        public string Root { get; init; }

        public string Name { get; init; }

        /// <summary>kscript or xml: the format the project writes scripts in (make.syntax).</summary>
        public string Format { get; init; } = MakeSettings.KScriptFormat;

        /// <summary>Every package a script in the project uses, KScript.Core first.</summary>
        public IReadOnlyList<string> Packages { get; init; } = new[] { "KScript.Core" };

        public IReadOnlyList<AgentSymbol> Symbols { get; init; } = Array.Empty<AgentSymbol>();

        /// <summary>The project's scripts (not tests or pages), relative, with / separators.</summary>
        public IReadOnlyList<string> Scripts { get; init; } = Array.Empty<string>();

        public int Tests { get; init; }

        public int Pages { get; init; }

        /// <summary>The site's declared routes, or null when there are none.</summary>
        public string Routes { get; init; }

        /// <summary>Markdown from the project's agents.merge files, in manifest order.</summary>
        public IReadOnlyList<string> Markdown { get; init; } = Array.Empty<string>();

        /// <summary>app.main from kscript.json, when set.</summary>
        public string Main { get; init; }

        public bool IsXml => Format == MakeSettings.XmlFormat;
    }

