        /// <summary>Every file <c>kscript agents</c> writes, by path relative to the project root, with its new text.</summary>
        public static IReadOnlyDictionary<string, string> Render(AgentProject project, LanguageCatalog catalog = null)
        {
            catalog ??= LanguageCatalog.Default;
            string agentsPath = Path.Combine(project.Root, AgentsFile);
            string existing = File.Exists(agentsPath) ? File.ReadAllText(agentsPath) : null;
            var files = new Dictionary<string, string>(StringComparer.Ordinal)
            {
                [AgentsFile] = Merge(existing, AgentsSection(project, catalog)),
                [Folder + "/index.md"] = Index(project),
            };
            foreach (string package in project.Packages)
            {
                files[$"{Folder}/packages/{package}.md"] = Package(package, catalog, project.Format);
            }
            // Preserve AGENTS.md's handwritten line endings. The generated reference files use LF.
            return files.ToDictionary(f => f.Key, f => f.Key == AgentsFile ? f.Value : f.Value.Replace("\r\n", "\n"), StringComparer.Ordinal);
        }

        /// <summary>
        /// Writes AGENTS.md and .kscript/agents for the project at <paramref name="root"/>, and removes package files
        /// for packages the project no longer uses. With <paramref name="check"/>, writes nothing. Returns the files
        /// that changed (or would change), relative to the root.
        /// </summary>
        public static IReadOnlyList<string> Write(string root, bool check = false, LanguageCatalog catalog = null, string format = null, ISet<string> skip = null)
        {
            AgentProject project = Read(root, catalog, format, skip);
            IReadOnlyDictionary<string, string> files = Render(project, catalog);
            var changed = new List<string>();
            foreach (var (relative, text) in files)
            {
                string path = Path.Combine(project.Root, relative);
                string old = File.Exists(path) ? File.ReadAllText(path) : null;
                if (relative != AgentsFile) old = old?.Replace("\r\n", "\n");
                if (old == text)
                {
                    continue;
                }
                changed.Add(relative);
                if (!check)
                {
                    Directory.CreateDirectory(Path.GetDirectoryName(path));
                    File.WriteAllText(path, text);
                }
            }

            string packagesFolder = Path.Combine(project.Root, Folder, "packages");
            if (Directory.Exists(packagesFolder))
            {
                foreach (string stale in Directory.GetFiles(packagesFolder, "KScript.*.md").OrderBy(path => path, StringComparer.Ordinal))
                {
                    string relative = $"{Folder}/packages/{Path.GetFileName(stale)}";
                    if (files.ContainsKey(relative)) continue;
                    changed.Add(relative);
                    if (!check) File.Delete(stale);
                }
            }
            return changed;
        }

